# Extra jobs in repository.yml beyond the shared policy check. Reusable code checks are
# enabled only once the repository actually contains the code, lockfile, and tests.
EXTRA_JOBS = {
    'vinoguessr-web': 'swift',
    'vinoguessr-infrastructure': 'terraform',
    'vinoguessr-docs': 'wiki-links',
}
COMMON = ['CLAUDE.md', 'CONTRIBUTING.md', 'SECURITY.md', '.github/CODEOWNERS', '.github/pull_request_template.md']
COMMON_GLOBS = ['.github/ISSUE_TEMPLATE/*.yml', '.codex/**/*.toml', '.claude/agents/*.md']
GITIGNORE_BASELINE = ['.DS_Store', '__pycache__/', '.env', '.env.*', '!.env.example', '.build/', '.swiftpm/', 'DerivedData/',
                      '*.xcuserstate', 'xcuserdata/', '.terraform/', '*.tfstate', '*.tfstate.*', '*.tfplan',
                      '*.tfvars', '!*.tfvars.example', '*.p12', '*.p8', '*.key', '*.pem']
README_MARKER = '<!-- vinoguessr-foundation -->'
README_END_MARKER = '<!-- /vinoguessr-foundation -->'
# The last line of sections generated before README_END_MARKER existed.
LEGACY_README_LAST_LINE = 'Follow [AGENTS.md](AGENTS.md) and [CONTRIBUTING.md](CONTRIBUTING.md): satisfy the Issue'
GITIGNORE_HEADING = '# VinoGuessr foundation baseline (vinoguessr/.github)'
CHECKOUT = 'actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1'


def repository_workflow(repo, sha):
    jobs = f"""  policy:
    uses: {ORG}/.github/.github/workflows/reusable-repository.yml@{sha}
    permissions:
      contents: read
"""
    extra = EXTRA_JOBS.get(repo)
    if extra == 'swift':
        jobs += f"""  swift:
    uses: {ORG}/.github/.github/workflows/reusable-swift.yml@{sha}
    permissions:
      contents: read
"""
    elif extra == 'terraform':
        jobs += f"""  terraform:
    uses: {ORG}/.github/.github/workflows/reusable-terraform.yml@{sha}
    permissions:
      contents: read
"""
    elif extra == 'wiki-links':
        jobs += f"""  wiki-links:
    name: Wiki links survive export
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - uses: {CHECKOUT}
        with:
          persist-credentials: false
      - run: python3 -m unittest discover -s scripts -v
"""
    return f"""name: Repository CI
on:
  pull_request:
  push:
    branches: [main, 'codex/**']
  workflow_dispatch:
permissions:
  contents: read
concurrency:
  group: repository-${{{{ github.workflow }}}}-${{{{ github.ref }}}}
  cancel-in-progress: true
jobs:
{jobs}"""


def agents(source, repo, sha):
    scope, architecture, verification = SCOPES[repo]
    text = (source / 'AGENTS.md').read_text().rstrip() + '\n'
    text += f'\n## {repo} specifics\n\nShared rules source: `{ORG}/.github@{sha}`.\n\n{scope}\n\n{architecture}\n\n{verification}\n'
    if repo == 'vinoguessr-app':
        text += '\n' + (source / 'policies/swiftui.md').read_text().rstrip() + '\n'
        text += f'\nSwiftUI policy source: `{ORG}/.github@{sha}:policies/swiftui.md`.\n'
    return text


def readme_section(repo, sha):
    scope, architecture, verification = SCOPES[repo]
    return (f'\n{README_MARKER}\n## Scope\n\n{scope}\n\n## Architecture\n\n{architecture}\n\n## Verification\n\n{verification}\n\n'
            f'Follow [AGENTS.md](AGENTS.md) and [CONTRIBUTING.md](CONTRIBUTING.md): satisfy the Issue\'s dependencies, then implement with an independent Review Agent running in parallel. '
            f'Shared rules source: [{ORG}/.github@{sha[:12]}](https://github.com/{ORG}/.github/tree/{sha}).\n'
            f'{README_END_MARKER}\n')


def generated_section_end(text, start):
    """End offset of the generated README section that begins at `start`."""
    end = text.find(README_END_MARKER, start)
    if end != -1:
        newline = text.find('\n', end)
        return len(text) if newline == -1 else newline + 1
    # Sections written before the end marker existed end with one exact generated line.
    for line_start in [m.start() for m in re.finditer(r'^', text[start:], re.M)]:
        line_start += start
        if text.startswith(LEGACY_README_LAST_LINE, line_start):
            newline = text.find('\n', line_start)
            return len(text) if newline == -1 else newline + 1
    raise RuntimeError(f'README.md has {README_MARKER} but no {README_END_MARKER}; restore the end marker by hand')


def gitignore_additions(lines):
    """Baseline lines to append. Later rules win in gitignore, so every baseline exception after a
    newly appended rule is appended again, even if the repository already has it."""
    additions, appended_rule = [], False
    for line in GITIGNORE_BASELINE:
        if line not in lines:
            additions.append(line)
            appended_rule = appended_rule or not line.startswith('!')
        elif line.startswith('!') and appended_rule:
            additions.append(line)
    return additions


def ensure_source_matches(source, sha):
    """The copied files must be exactly the commit named in the generated `Shared rules source` lines."""
    head = subprocess.run(['git', '-C', str(source), 'rev-parse', 'HEAD'], capture_output=True, text=True)
    if head.returncode or head.stdout.strip() != sha:
        raise RuntimeError(f'{source} is not checked out at {sha}')
    status = subprocess.run(['git', '-C', str(source), 'status', '--porcelain'], capture_output=True, text=True)
    if status.returncode or status.stdout.strip():
        raise RuntimeError(f'{source} has uncommitted changes; sync from a clean checkout')


def ensure_durable(sha):
    """Reusable workflow calls break once an unmerged branch is deleted, so only main history is allowed."""
    result = subprocess.run(['gh', 'api', f'repos/{ORG}/.github/compare/{sha}...main'], capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(f'Cannot compare {sha} with main: {result.stderr.strip()}')
    comparison = json.loads(result.stdout)
    if comparison.get('status') not in {'ahead', 'identical'} or comparison.get('merge_base_commit', {}).get('sha') != sha:
        raise RuntimeError(f'{sha} is not in the history of vinoguessr/.github main')


def sync(source, sha, repo, target):
    if not re.fullmatch(r'[0-9a-f]{40}', sha):
        raise ValueError('--sha must be a 40-character commit SHA')
    files = list(COMMON)
    for pattern in COMMON_GLOBS:
        files += [str(p.relative_to(source)) for p in sorted(source.glob(pattern))]
    for rel in files:
        (target / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source / rel, target / rel)
    if not (target / 'LICENSE').exists():
        shutil.copyfile(source / 'LICENSE', target / 'LICENSE')
    (target / 'AGENTS.md').write_text(agents(source, repo, sha))
    workflows = target / '.github/workflows'
    workflows.mkdir(parents=True, exist_ok=True)
    (workflows / 'repository.yml').write_text(repository_workflow(repo, sha))
    shutil.copyfile(source / '.github/workflows/verify-lockfile.yml', workflows / 'verify-lockfile.yml')
    readme = target / 'README.md'
    original = readme.read_text() if readme.exists() else f'# {repo}\n'
    if README_MARKER in original:
        start = original.index(README_MARKER)
        end = generated_section_end(original, start)
        readme.write_text(original[:start].rstrip() + '\n' + readme_section(repo, sha) + original[end:])
    else:
        readme.write_text(original.rstrip() + '\n' + readme_section(repo, sha))
    gitignore = target / '.gitignore'
    lines = gitignore.read_text().splitlines() if gitignore.exists() else []
    missing = gitignore_additions(lines)
    if missing:
        heading = [GITIGNORE_HEADING] if GITIGNORE_HEADING not in lines else []
        separator = [''] if lines and (lines[-1].strip() or heading) else []
        gitignore.write_text('\n'.join(lines + separator + heading + missing).strip() + '\n')
    dependabot = target / '.github/dependabot.yml'
    if not dependabot.exists():
        dependabot.write_text("""version: 2
updates:
  - package-ecosystem: github-actions
    directory: /
    schedule:
      interval: weekly
    cooldown:
      default-days: 7
    open-pull-requests-limit: 5
""")
    print(subprocess.run(['git', 'status', '--short'], cwd=target, capture_output=True, text=True).stdout)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--source', type=Path, default=ROOT, help='.github checkout at --sha (default: this repository)')
    p.add_argument('--sha', required=True)
    p.add_argument('--repo', required=True, choices=list(SCOPES))
    p.add_argument('--target', type=Path, required=True)
    a = p.parse_args()
    ensure_durable(a.sha)
    ensure_source_matches(a.source.resolve(), a.sha)
    sync(a.source.resolve(), a.sha, a.repo, a.target.resolve())


if __name__ == '__main__':
    main()
